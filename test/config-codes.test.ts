describe("the structured problem codes", () => {
  it("are exactly the pinned list, sorted and unique", () => {
    const found = [...new Set(codesOf(join(import.meta.dirname, "../src")))].sort();
    assert.deepEqual(found, PINNED);
    assert.equal(new Set(PINNED).size, PINNED.length, "no code is listed twice");
  });

  it("are reused across sites only by the two validators that answer the same problem twice", () => {
    const all = codesOf(join(import.meta.dirname, "../src"));
    const reused = [...new Set(all.filter((code, i) => all.indexOf(code) !== i))].sort();
    assert.deepEqual(reused, ["paylink.connect_needs_account", "trace.step_unknown_field"]);
  });
});
