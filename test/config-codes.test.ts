// The structured problem codes are API from 0.4.0: a dashboard localizes by them, so the full list
// is pinned here. A code names a problem, not a call site: two sites may answer the same code only
// when they answer the same problem (today only paylink.connect_needs_account, answered by the
// settings and the step validator, and trace.step_unknown_field, answered by both trace steps).
// A new code joins this list in the same change; a code is never reused for a different problem.
import { strict as assert } from "node:assert";
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, it } from "node:test";

/** Every problem("...") call and inline code literal in src/, with repeats when sites share a code. */
function codesOf(dir: string): string[] {
  const found: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const at = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...codesOf(at));
    else if (entry.name.endsWith(".ts")) {
      const text = readFileSync(at, "utf8");
      for (const m of text.matchAll(/problem\("([a-z][a-z0-9_.]*)"/g)) found.push(m[1]!);
      for (const m of text.matchAll(/code: "([a-z][a-z0-9_.]*)"/g)) found.push(m[1]!);
    }
  }
  return found;
}

